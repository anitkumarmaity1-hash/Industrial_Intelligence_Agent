-- Industrial Intelligence Agent — schema (multi-tenant since 0002; generic sensors 0005; row-level security 0006)
--
-- Reflects what the Phase 1 PySpark pipeline actually produces (verified
-- against data/processed/*.parquet), not the original Phase 0 sketch.
-- Deviations from Phase 0 are called out inline.
--
-- This file is the FULL CURRENT SCHEMA, used by docker-compose's init
-- script and CI. It must stay identical to what `alembic upgrade head`
-- produces (tests/test_migrations.py checks this). To change the schema:
-- add an Alembic migration under migrations/versions/, then update this
-- file to match.
--
-- Multi-tenancy (production-readiness fix 1): every table that holds a
-- company's data carries `tenant_id`, and every query in
-- app/database/queries.py filters on it. Machine ids are unique per
-- tenant, not globally, so two companies can both own an "M-01".
-- `ai4i_reference` is deliberately NOT tenant-scoped: it is the public UCI
-- AI4I 2020 dataset, shared read-only reference data, not company data.
--
-- `tenant_id ... DEFAULT 'default'` exists only so the committed seed
-- (sql/seed.sql.gz, a COPY dump written before tenancy that names its
-- columns explicitly) still loads into the demo tenant. Application code
-- never relies on it: queries pass tenant_id explicitly, and loaders take
-- an explicit --tenant.

-- ---------------------------------------------------------------------
-- tenants — one row per company; holds the hashed API credential
-- ---------------------------------------------------------------------
-- api_key_hash is SHA-256 of a random 256-bit key (see
-- app/core/tenancy.hash_api_key); the key itself is never stored. NULL
-- means "no credential issued yet" — that tenant cannot authenticate.
CREATE TABLE tenants (
    tenant_id      VARCHAR(48)  PRIMARY KEY CHECK (tenant_id ~ '^[a-z0-9][a-z0-9_-]{0,47}$'),
    name           VARCHAR(200) NOT NULL,
    api_key_hash   CHAR(64)     UNIQUE,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP    NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);

