-- ---------------------------------------------------------------------
-- sensor_readings — long-format raw readings (0005). Partitioned by
-- RANGE(ts) with a single DEFAULT partition, same approach and reasoning
-- as sensor_summary/machine_anomalies (0004); scripts/manage_partitions.py
-- adds monthly partitions. The PRIMARY KEY is the idempotency key: loaders
-- INSERT ... ON CONFLICT on it, so re-running a load never duplicates rows.
-- ---------------------------------------------------------------------
CREATE TABLE sensor_readings (
    tenant_id    VARCHAR(48)      NOT NULL,
    machine_id   VARCHAR(64)      NOT NULL,
    sensor_name  VARCHAR(64)      NOT NULL,
    ts           TIMESTAMP        NOT NULL,
    value        DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (tenant_id, machine_id, sensor_name, ts),
    FOREIGN KEY (tenant_id, machine_id) REFERENCES machines (tenant_id, machine_id),
    FOREIGN KEY (tenant_id, sensor_name) REFERENCES sensor_registry (tenant_id, sensor_name)
) PARTITION BY RANGE (ts);

CREATE TABLE sensor_readings_default PARTITION OF sensor_readings DEFAULT;

CREATE INDEX idx_sensor_readings_tenant_ts ON sensor_readings (tenant_id, ts);

-- ---------------------------------------------------------------------
-- Row-level security (0006, Phase 2): tenant isolation enforced by Postgres.
-- Policies compare tenant_id with the transaction-local setting
-- `app.tenant_id` (app/database/tenant_context.py); unset = no rows, writes
-- fail. FORCE applies the policies to the table owner too (superusers and
-- BYPASSRLS roles still bypass). `tenants` and `ai4i_reference` stay outside
-- RLS; the API role (`iia_app`, least privilege, LOGIN set by
-- scripts/provision_app_role.py) reaches `tenants` only via the SECURITY
-- DEFINER auth_lookup_tenant(). iia_enable_tenant_rls() is also called for
-- each partition scripts/manage_partitions.py creates.
-- ---------------------------------------------------------------------
CREATE FUNCTION iia_enable_tenant_rls(tbl regclass) RETURNS void
LANGUAGE plpgsql AS $fn$
BEGIN
    EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY', tbl);
    EXECUTE format('ALTER TABLE %s FORCE ROW LEVEL SECURITY', tbl);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %s', tbl);
    EXECUTE format($q$CREATE POLICY tenant_isolation ON %s
                       USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')) WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), ''))$q$, tbl);
END
$fn$;

CREATE FUNCTION auth_lookup_tenant(p_hash text)
RETURNS TABLE (tenant_id varchar, name varchar)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, public AS $fn$
    SELECT t.tenant_id, t.name FROM public.tenants t
    WHERE t.api_key_hash = p_hash AND t.active
$fn$;

CREATE FUNCTION iia_grant_app_privileges() RETURNS void
LANGUAGE plpgsql AS $fn$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'iia_app') THEN
        CREATE ROLE iia_app NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
    END IF;
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM iia_app;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM iia_app;
    GRANT USAGE ON SCHEMA public TO iia_app;
    GRANT SELECT ON machines, sensor_summary, machine_anomalies, maintenance_records,
        sensor_registry, sensor_readings, tenant_settings, ai4i_reference TO iia_app;
    GRANT INSERT ON investigation_audit_log TO iia_app;
    GRANT USAGE ON SEQUENCE investigation_audit_log_id_seq TO iia_app;
    REVOKE ALL ON FUNCTION auth_lookup_tenant(text) FROM PUBLIC;
    GRANT EXECUTE ON FUNCTION auth_lookup_tenant(text) TO iia_app;
    REVOKE ALL ON FUNCTION iia_enable_tenant_rls(regclass) FROM PUBLIC;
    REVOKE ALL ON FUNCTION iia_grant_app_privileges() FROM PUBLIC;
END
$fn$;

